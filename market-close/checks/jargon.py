# 태그(#국장·#미장)는 검색어라 예외다 — 본문 낱말로 쓰는 것만 막는다.
_TAG_OK = ("#국장", "#미장")


def find(text: str) -> list[str]:
    """본문/답글에서 걸린 낱말. 빈 리스트면 통과."""
    if not text:
        return []
    t = text
    for tag in _TAG_OK:
        t = t.replace(tag, "")
    return [w for w in BAN if w in t]


def why(word: str) -> str:
    """걸린 낱말을 어떻게 바꾸는지."""
